// Паттерн «Компоновщик» (Composite)
//
// Идея паттерна: отдельные объекты и группы объектов имеют общий интерфейс.
// Поэтому клиентский код может одинаково работать и с файлом, и с папкой.
//
// В этом примере:
// - File — «лист» (Leaf), то есть конечный объект без вложенных элементов;
// - Folder — «компоновщик» (Composite), который может содержать листья
//   и другие компоновщики;
// - IFileSystemItem — общий компонент (Component), объединяющий их
//   общим методом Show().
//
// Такая структура особенно удобна для древовидных данных: файловой системы,
// меню, каталога товаров или структуры подразделений компании.

// Общий компонент для всех элементов файловой системы.
// Клиенту не нужно знать конкретный тип объекта — достаточно знать,
// что любой элемент умеет выполнить Show().
interface IFileSystemItem
{
    // Параметр indent хранит текущий уровень вложенности.
    // Значение по умолчанию позволяет вызвать Show() для корневого элемента
    // без явной передачи отступа.
    void Show(int indent = 0);
}

// Лист — отдельный объект, у которого нет вложенных элементов.
// File реализует тот же интерфейс, что и Folder, поэтому файл можно
// добавлять в папку и обрабатывать через ссылку IFileSystemItem.
class File : IFileSystemItem
{
    private readonly string _name;

    public File(string name)
    {
        _name = name;
    }

    public void Show(int indent = 0)
    {
        // Отступ показывает уровень вложенности файла в дереве.
        // Сам файл не вызывает Show() у других объектов, потому что
        // является конечным элементом и не содержит дочерних элементов.
        Console.WriteLine($"{new string(' ', indent)}- Файл: {_name}");
    }
}

// Компоновщик — объект, который может содержать файлы и другие папки.
// Благодаря списку IFileSystemItem папка не привязана к конкретному классу:
// в неё можно положить как File, так и Folder.
class Folder : IFileSystemItem
{
    private readonly string _name;
    private readonly List<IFileSystemItem> _items = new();

    public Folder(string name)
    {
        _name = name;
    }

    public void Add(IFileSystemItem item)
    {
        // В список добавляется общий тип интерфейса.
        // Это и есть основа полиморфизма: конкретный тип элемента
        // будет выбран во время выполнения программы.
        _items.Add(item);
    }

    public void Remove(IFileSystemItem item)
    {
        // Удаляем переданный элемент из непосредственного содержимого папки.
        // Вложенные папки при этом не просматриваются автоматически.
        _items.Remove(item);
    }

    public void Show(int indent = 0)
    {
        // Сначала выводим саму папку, затем её содержимое.
        Console.WriteLine($"{new string(' ', indent)}+ Папка: {_name}");

        // Для каждого вложенного элемента вызывается один и тот же метод Show().
        // Нам не нужно проверять, файл это или папка:
        // - File выведет одну строку;
        // - Folder выведет себя и продолжит обход своего содержимого.
        //
        // Вызов Folder.Show() для вложенной папки запускает рекурсию:
        // каждый следующий уровень получает увеличенный отступ.
        foreach (IFileSystemItem item in _items)
        {
            item.Show(indent + 4);
        }
    }
}

class Program
{
    static void Main()
    {
        // Создаём отдельные объекты-листья.
        // Они не знают о папках, в которые будут добавлены.
        File document = new("document.txt");
        File photo = new("photo.jpg");
        File program = new("program.cs");

        // Создаём объекты-компоновщики.
        // Папка может быть пустой, а её содержимое добавляется отдельно
        // через метод Add().
        Folder documents = new("Документы");
        Folder pictures = new("Изображения");
        Folder pictures2 = new("Изображения 2");
        Folder root = new("Мой компьютер");

        // Формируем первый уровень дерева.
        documents.Add(document);
        pictures.Add(photo);
        pictures.Add(pictures2);

        // Добавляем вложенную папку в папку.
        // Это показывает, что Composite может содержать другой Composite.
        pictures2.Add(document);

        // Добавляем файл и папки в корневую папку.
        root.Add(program);
        root.Add(documents);
        root.Add(pictures);

        // Клиентский код работает с корневой папкой через общий интерфейс.
        // Папка сама выведет себя и все вложенные элементы рекурсивно.
        root.Show();
        Console.WriteLine();

        // Можно вывести не всё дерево, а только отдельную папку.
        // Обратите внимание: один и тот же объект document добавлен
        // в две разные папки, поэтому при выводе он появится в обоих местах.
        pictures.Show();
    }
}
